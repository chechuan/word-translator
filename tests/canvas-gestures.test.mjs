import test from "node:test";
import assert from "node:assert/strict";
import { CanvasTouchGesture, resolveCanvasWheel } from "../lib/canvas-gestures.ts";

const wheel = { deltaX: 0, deltaY: 80, deltaMode: 0, ctrlKey: false, altKey: false, shiftKey: false };
const viewport = { width: 900, height: 600 };
test("默认触控板双指滑动只平移，捏合和 Option＋滚动仍缩放", () => {
  assert.deepEqual(resolveCanvasWheel(wheel, 'pan', viewport), { kind: 'pan', dx: 0, dy: 80 });
  assert.deepEqual(resolveCanvasWheel({ ...wheel, deltaX: 35, deltaY: -20 }, 'pan', viewport), { kind: 'pan', dx: 35, dy: -20 });
  const pinch = resolveCanvasWheel({ ...wheel, deltaY: -5, ctrlKey: true }, 'pan', viewport);
  assert.equal(pinch.kind, 'zoom');
  assert.ok(pinch.factor > 1);
  assert.equal(resolveCanvasWheel({ ...wheel, altKey: true }, 'pan', viewport).kind, 'zoom');
  assert.equal(resolveCanvasWheel(wheel, 'zoom', viewport).kind, 'zoom');
});
test("滚动支持鼠标行单位和整页单位，Shift＋滚动可以横向移动", () => {
  assert.deepEqual(resolveCanvasWheel({ ...wheel, deltaY: 3, deltaMode: 1 }, 'pan', viewport), { kind: 'pan', dx: 0, dy: 48 });
  assert.deepEqual(resolveCanvasWheel({ ...wheel, deltaX: 1, deltaY: 1, deltaMode: 2 }, 'pan', viewport), { kind: 'pan', dx: 900, dy: 600 });
  assert.deepEqual(resolveCanvasWheel({ ...wheel, shiftKey: true }, 'pan', viewport), { kind: 'pan', dx: 80, dy: 0 });
});

function near(actual, expected) { assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`); }
const camera = { x: 20, y: 30, zoom: 0.4 };

test("单指轻触保持节点可点击，超过移动阈值后才拖动画布", () => {
  const gesture = new CanvasTouchGesture();
  gesture.start(1, { x: 100, y: 100 }, camera);
  assert.equal(gesture.move(1, { x: 102, y: 101 }), null);
  assert.equal(gesture.didMove, false);
  assert.deepEqual(gesture.move(1, { x: 120, y: 130 }), { ...camera, x: 40, y: 60 });
  assert.equal(gesture.didMove, true);
  gesture.end(1, camera);
  assert.equal(gesture.didMove, true); // Suppress the click generated by this drag.
  gesture.start(2, { x: 100, y: 100 }, camera);
  assert.equal(gesture.didMove, false); // The next deliberate tap still works.
});

test("第二根手指触发缩放，张开时放大并保持两指中心的图上位置", () => {
  const gesture = new CanvasTouchGesture();
  gesture.start(10, { x: 100, y: 100 }, camera);
  gesture.start(20, { x: 200, y: 100 }, camera);
  assert.equal(gesture.didMove, true);
  const next = gesture.move(20, { x: 300, y: 100 });
  near(next.zoom, 0.8);
  near((200 - next.x) / next.zoom, (150 - camera.x) / camera.zoom);
  near((100 - next.y) / next.zoom, (100 - camera.y) / camera.zoom);
});

test("合拢时缩小，缩放达到上下限后仍围绕手指位置移动", () => {
  const gesture = new CanvasTouchGesture();
  const initial = { x: 0, y: 0, zoom: 1 };
  gesture.start(1, { x: 100, y: 100 }, initial);
  gesture.start(2, { x: 200, y: 100 }, initial);
  const smaller = gesture.move(2, { x: 150, y: 100 });
  near(smaller.zoom, 0.5);
  const maximum = gesture.move(2, { x: 1000, y: 100 });
  near(maximum.zoom, 1.8);
  near((550 - maximum.x) / maximum.zoom, 150);
  const minimum = gesture.move(2, { x: 101, y: 100 });
  near(minimum.zoom, 0.1);
  near((100.5 - minimum.x) / minimum.zoom, 150);
});

test("双指也可同时平移，抬起一根后继续单指拖动不跳回原位", () => {
  const gesture = new CanvasTouchGesture();
  gesture.start(1, { x: 100, y: 100 }, camera);
  gesture.start(2, { x: 200, y: 100 }, camera);
  gesture.move(1, { x: 120, y: 130 });
  const translated = gesture.move(2, { x: 220, y: 130 });
  assert.deepEqual(translated, { ...camera, x: 40, y: 60 });
  gesture.end(2, translated);
  assert.deepEqual(gesture.move(1, { x: 125, y: 140 }), { ...camera, x: 45, y: 70 });
  assert.equal(gesture.has(2), false);
});

test("触点取消或离开页面后可重新开始，旧触点不会继续控制画布", () => {
  const gesture = new CanvasTouchGesture();
  gesture.start(1, { x: 10, y: 20 }, camera);
  gesture.start(2, { x: 110, y: 20 }, camera);
  gesture.end(1, camera);
  assert.deepEqual(gesture.move(2, { x: 120, y: 40 }), { ...camera, x: 30, y: 50 });
  gesture.clear();
  assert.deepEqual(gesture.pointerIds, []);
  assert.equal(gesture.move(2, { x: 500, y: 500 }), null);
  gesture.start(3, { x: 10, y: 10 }, camera);
  assert.equal(gesture.didMove, false);
  assert.deepEqual(gesture.move(3, { x: 20, y: 20 }), { ...camera, x: 30, y: 40 });
});
